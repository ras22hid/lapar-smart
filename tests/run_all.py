# -*- coding: utf-8 -*-
"""Runs the whole automated test suite with one command, no human steps and no real credentials.

    python tests/run_all.py                 # regression suite + browser tests (28 manual cases)
    python tests/run_all.py --no-e2e        # regression suite only (no browser needed)

What it does
  1. regression.py : Flask test client against a temporary SQLite database (138 checks).
  2. serve_test.py : starts the app on a free port with its own temporary database.
  3. e2e.py        : drives a real browser (Playwright) through the 28 functional and regression cases,
                     with screenshots and a results.json in tests/output/.

Gmail is never used: the app's mail sender is replaced by a stub that records each email in a file,
and smtplib.SMTP is blocked, so no email can be sent. Test accounts and passwords are generated by the
tests themselves. Optional settings go in tests/.env.test (git-ignored) or the environment:
    LAPAR_TEST_EMAIL        address used for the Chief Clerk's emails (recorded, never sent)
    LAPAR_BROWSER_CHANNEL   browser channel for Playwright (default: msedge on Windows, bundled chromium elsewhere)
    LAPAR_APP_PYTHON        python used for the app (regression suite and test server) when it differs from
                            the one that has Playwright; default: the python running this script
Exit code is 0 only when every check and every browser case passes.
"""
import argparse, json, os, re, shutil, socket, subprocess, sys, tempfile, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "output")


def load_env_file():
    path = os.path.join(HERE, ".env.test")
    if not os.path.exists(path):
        return
    for line in open(path, encoding="utf-8-sig"):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip().strip('"'))


APP_PY = None


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def clean_env():
    env = dict(os.environ)
    for k in ("TURSO_DATABASE_URL", "TURSO_AUTH_TOKEN", "GMAIL_ADDRESS", "GMAIL_APP_PASSWORD", "VERCEL"):
        env.pop(k, None)  # never let a real database or mail account be used by the tests
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def run_regression():
    p = subprocess.run([APP_PY, os.path.join(HERE, "regression.py")], capture_output=True, text=True,
                       encoding="utf-8", errors="replace", env=clean_env())
    open(os.path.join(OUT, "regression.txt"), "w", encoding="utf-8").write(p.stdout + p.stderr)
    m = re.search(r"(\d+)/(\d+) checks passed", p.stdout)
    passed, total = (int(m.group(1)), int(m.group(2))) if m else (0, 0)
    failed = [l for l in p.stdout.splitlines() if l.startswith("FAIL")]
    return {"name": "Regression suite (Flask test client)", "passed": passed, "total": total,
            "ok": p.returncode == 0 and total > 0 and passed == total, "failed": failed}


def run_e2e(tmp):
    db = os.path.join(tmp, "e2e.db")
    port = free_port()
    base = f"http://127.0.0.1:{port}"
    log = open(os.path.join(OUT, "server.log"), "w", encoding="utf-8")
    srv = subprocess.Popen([APP_PY, os.path.join(HERE, "serve_test.py"), db, str(port)],
                           stdout=log, stderr=subprocess.STDOUT, env=clean_env())
    try:
        for _ in range(60):
            try:
                urllib.request.urlopen(base + "/", timeout=2)
                break
            except Exception:
                if srv.poll() is not None:
                    raise RuntimeError("test server exited early, see tests/output/server.log")
                time.sleep(0.5)
        else:
            raise RuntimeError("test server did not start")
        env = clean_env()
        env.update({"LAPAR_TEST_BASE": base, "LAPAR_TEST_DB": db, "LAPAR_TEST_OUT": OUT})
        p = subprocess.run([sys.executable, os.path.join(HERE, "e2e.py")], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", env=env)
        open(os.path.join(OUT, "e2e.txt"), "w", encoding="utf-8").write(p.stdout + p.stderr)
    finally:
        srv.terminate()
        try:
            srv.wait(timeout=10)
        except Exception:
            srv.kill()
        log.close()
    res_path = os.path.join(OUT, "results.json")
    res = json.load(open(res_path, encoding="utf-8")) if os.path.exists(res_path) else {}
    failed = [k for k, v in res.items() if v["status"] != "Pass"]
    passed = len(res) - len(failed)
    return {"name": "Browser tests (28 functional and regression cases)", "passed": passed, "total": 28,
            "ok": p.returncode == 0 and len(res) == 28 and not failed,
            "failed": failed or ([] if res else ["no results produced, see tests/output/e2e.txt"])}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-e2e", action="store_true", help="skip the browser tests")
    ap.add_argument("--no-regression", action="store_true", help="skip the regression suite")
    args = ap.parse_args()
    load_env_file()
    global APP_PY
    APP_PY = os.environ.get("LAPAR_APP_PYTHON") or sys.executable
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix="lapar-tests-")
    rows = []
    t0 = time.time()
    try:
        if not args.no_regression:
            rows.append(run_regression())
        if not args.no_e2e:
            rows.append(run_e2e(tmp))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    lines = []
    for r in rows:
        lines.append(f"{'PASS' if r['ok'] else 'FAIL'}  {r['name']}: {r['passed']}/{r['total']}")
        for f in r["failed"]:
            lines.append(f"      {f}")
    lines.append(f"Finished in {time.time() - t0:.0f} s. Details and screenshots: tests/output/")
    text = "\n".join(lines)
    print(text)
    open(os.path.join(OUT, "summary.txt"), "w", encoding="utf-8").write(text + "\n")
    sys.exit(0 if rows and all(r["ok"] for r in rows) else 1)


if __name__ == "__main__":
    main()
